import {readFileSync,writeFileSync} from 'node:fs';
import {join} from 'node:path';
import {fileURLToPath} from 'node:url';
import {nextVersion,requireIncrement} from './version-policy.mjs';
const root=fileURLToPath(new URL('../',import.meta.url));
const prior=readFileSync(join(root,'VERSION'),'utf8').trim();
const version=process.argv[2]||nextVersion(prior);
requireIncrement(prior,version);
const file=join(root,'catalog.json');
const catalog=JSON.parse(readFileSync(file,'utf8'));
if(catalog.version!==prior)throw Error('VERSION and catalog version mismatch.');
catalog.version=version;
writeFileSync(file,JSON.stringify(catalog,null,2)+'\n');
writeFileSync(join(root,'VERSION'),version+'\n');
const readme=join(root,'README.md');
writeFileSync(readme,readFileSync(readme,'utf8').replace('catalog `'+prior+'`','catalog `'+version+'`'));
writeFileSync(join(root,'RELEASE.md'),'# ATGV SDLC Library v'+version+'\n\n## Changes\n\n- Record reviewed changes.\n');
console.log('Updated Library to '+version+' and overwrote RELEASE.md');
